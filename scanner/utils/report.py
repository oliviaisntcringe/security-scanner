_ROW_TEMPLATE = """\
    <tr>
      <td>{i}</td>
      <td><span class="badge" style="background:{color}">{severity}</span></td>
      <td><strong>{vtype}</strong></td>
      <td>{param}</td>
      <td class="evidence">{payload}</td>
      <td>{url}</td>
      <td class="evidence">{evidence}</td>
    </tr>
"""


def generate(
    target: str,
    findings: List[Dict[str, Any]],
    urls_crawled: int = 0,
    elapsed: float = 0.0,
    fmt: str = "html",
    output: Path | None = None,
) -> Path:
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    if output is None:
        suffix = {"html": ".html", "json": ".json", "txt": ".txt"}.get(fmt, ".txt")
        output = REPORTS_DIR / f"vulnscan_{ts}{suffix}"

    if fmt == "html":
        content = _html(target, findings, urls_crawled, elapsed, ts)
    elif fmt == "json":
        content = _json(target, findings, urls_crawled, elapsed, ts)
    else:
        content = _text(target, findings, urls_crawled, elapsed, ts)

    output.write_text(content, encoding="utf-8")
    return output


# ── Format builders ────────────────────────────────────────────────────────────

def _counts(findings):
    c = {"critical": 0, "high": 0, "medium": 0, "low": 0}
    for f in findings:
        sev = f.get("severity", severity_of(f.get("type", "")))
        c[sev] = c.get(sev, 0) + 1
    return c


def _html(target, findings, urls_crawled, elapsed, ts) -> str:
    c = _counts(findings)
    rows = ""
    for i, f in enumerate(findings, 1):
        vtype = f.get("type", "?")
        sev   = f.get("severity", severity_of(vtype))
        rows += _ROW_TEMPLATE.format(
            i=i,
            color=SEVERITY_COLORS.get(sev, "#475569"),
            severity=sev.upper(),
            vtype=vtype.upper(),
            param=_esc(f.get("parameter", "N/A")),
            payload=_esc(str(f.get("payload", "N/A"))[:120]),
            url=_esc(f.get("url", "N/A")),
            evidence=_esc(str(f.get("evidence", ""))[:200]),
        )
    return _HTML_TEMPLATE.format(
        target=_esc(target),
        timestamp=ts,
        elapsed=f"{elapsed:.1f}",
        urls_crawled=urls_crawled,
        total=len(findings),
        rows=rows,
        **c,
    )


def _json(target, findings, urls_crawled, elapsed, ts) -> str:
    return json.dumps({
        "target":       target,
        "timestamp":    ts,
        "elapsed":      round(elapsed, 2),
        "urls_crawled": urls_crawled,
        "total":        len(findings),
        "findings":     findings,
    }, indent=2, ensure_ascii=False)


def _text(target, findings, urls_crawled, elapsed, ts) -> str:
    lines = [
        f"VulnScan Report — {target}",
        f"Scanned: {ts}  Duration: {elapsed:.1f}s  URLs: {urls_crawled}",
        "=" * 60,
    ]
    c = _counts(findings)
    lines.append(f"Total: {len(findings)}  " +
                 "  ".join(f"{k.upper()}: {v}" for k, v in c.items()))
    lines.append("")
    for i, f in enumerate(findings, 1):
        vtype = f.get("type", "?")
        sev   = f.get("severity", severity_of(vtype))
        lines += [
            f"[{i}] {sev.upper()} — {vtype.upper()}",
            f"    URL:      {f.get('url', 'N/A')}",
            f"    Param:    {f.get('parameter', 'N/A')}",
            f"    Payload:  {str(f.get('payload','N/A'))[:100]}",
            f"    Evidence: {str(f.get('evidence',''))[:200]}",
            "",
        ]
    return "\n".join(lines)


def _esc(s: str) -> str:
    return (s.replace("&", "&amp;")
             .replace("<", "&lt;")
             .replace(">", "&gt;")
             .replace('"', "&quot;"))
