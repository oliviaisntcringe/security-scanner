"""
Report generation — HTML, JSON, plain text.
"""
from __future__ import annotations

import json
import time
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any

from scanner.config import REPORTS_DIR
from scanner.utils.output import severity_of

SEVERITY_COLORS = {
    "critical": "#dc2626",
    "high":     "#ea580c",
    "medium":   "#ca8a04",
    "low":      "#16a34a",
    "info":     "#2563eb",
}

